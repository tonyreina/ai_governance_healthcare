# The app's newId() produces "p" + base36 time + 5 random chars. Imported or
# hand-made ids are also allowed, within reason: this keeps a path segment from
# carrying a slash, a dot-dot, or four kilobytes.
ProjectId = Path(
    ...,
    min_length=1,
    max_length=64,
    pattern=r"^[A-Za-z0-9_.:-]+$",
    description="Project id, as generated by the app's newId().",
)


