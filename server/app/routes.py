"""Every endpoint in the store contract, and nothing else.

The browser persists through six methods. Each maps to one route:

================================  ==========================================
``subscribeAll(cb, err)``         ``GET /api/projects`` + ``GET /api/events``
``create(id, data)``              ``POST /api/projects/{id}``
``update(id, patch)``             ``PATCH /api/projects/{id}``
``remove(id)``                    ``DELETE /api/projects/{id}``
``log(id, entry)``                ``POST /api/projects/{id}/log``
``subscribeLog(id, cb)``          ``GET /api/projects/{id}/log`` + events
================================  ==========================================

The two ``subscribe*`` methods are a fetch plus a stream: the client fetches
once, then holds ``/api/events`` open and refetches whatever an event says
changed.
"""

